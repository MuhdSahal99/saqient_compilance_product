"""Private object storage behind a small adapter interface.

Keys are always generated by the application (``{org_id}/{uuid}``); user
filenames never reach the storage layer.
"""

from __future__ import annotations

import os
import uuid
from abc import ABC, abstractmethod
from functools import lru_cache
from pathlib import Path

from app.config import get_settings


class StorageError(RuntimeError):
    pass


class StorageAdapter(ABC):
    @abstractmethod
    def put(self, key: str, data: bytes) -> None: ...

    @abstractmethod
    def get(self, key: str) -> bytes: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...


def new_storage_key(org_id: uuid.UUID) -> str:
    return f"{org_id}/{uuid.uuid4().hex}"


class LocalStorage(StorageAdapter):
    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True, mode=0o700)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        tmp = path.with_suffix(".tmp")
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o600)
        tmp.replace(path)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("object not found") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).exists()


class S3Storage(StorageAdapter):  # pragma: no cover - optional, not exercised in CI
    def __init__(self, bucket: str, endpoint_url: str | None, region: str | None) -> None:
        import boto3

        self.bucket = bucket
        self.client = boto3.client("s3", endpoint_url=endpoint_url or None, region_name=region)

    def put(self, key: str, data: bytes) -> None:
        self.client.put_object(
            Bucket=self.bucket, Key=key, Body=data, ServerSideEncryption="AES256"
        )

    def get(self, key: str) -> bytes:
        return bytes(self.client.get_object(Bucket=self.bucket, Key=key)["Body"].read())

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except Exception:
            return False


class GCSStorage(StorageAdapter):  # pragma: no cover - optional, not exercised in CI
    def __init__(self, bucket: str) -> None:
        from google.cloud import storage

        self.bucket = storage.Client().bucket(bucket)

    def put(self, key: str, data: bytes) -> None:
        self.bucket.blob(key).upload_from_string(data)

    def get(self, key: str) -> bytes:
        return bytes(self.bucket.blob(key).download_as_bytes())

    def delete(self, key: str) -> None:
        self.bucket.blob(key).delete()

    def exists(self, key: str) -> bool:
        return bool(self.bucket.blob(key).exists())


@lru_cache
def get_storage() -> StorageAdapter:
    s = get_settings()
    if s.storage_backend == "s3":
        return S3Storage(s.s3_bucket, s.s3_endpoint_url, s.s3_region)
    if s.storage_backend == "gcs":
        return GCSStorage(s.gcs_bucket)
    return LocalStorage(s.storage_local_path)
